package server

import (
	"context"
	"fmt"
	"sync"
	"time"

	"sentinel-linux/internal/link"
	"sentinel-linux/internal/store"
)

// Low-disk alarm (Mac kind "Storage"), so rules can route "disk almost full"
// like any other alarm. The recording server watches its disk (under 5%
// free: storage.low; back over 8%: storage.recovered); the alarm is raised
// once and noted when space recovers.

type storageState struct {
	mu     sync.Mutex
	openID map[string]string // recording server id → open Storage alarm
}

func (s *Server) onStorage(ctx context.Context, serverID, typ string, h link.Storage) error {
	st := &s.storage
	st.mu.Lock()
	defer st.mu.Unlock()
	if st.openID == nil {
		st.openID = map[string]string{}
	}
	open := st.openID[serverID]
	switch {
	case typ == link.EventStorageLow && open == "":
		a, _, err := s.Store.RaiseAlarm(ctx, store.AlarmInput{
			Kind: "Storage", Title: "Storage almost full", Severity: "Critical",
			Detail: fmt.Sprintf("Only %.1f GB (%.1f%%) is free on the recordings disk. Free up space or shorten retention, or recording will stop.", float64(h.FreeBytes)/1e9, h.FreePct),
			At:     time.Now(), Origin: "Automatically generated by storage monitor",
		})
		if err != nil {
			return err // not taken: the recorder retries
		}
		st.openID[serverID] = a.ID
	case typ == link.EventStorageRecovered && open != "":
		_ = s.Store.AddAlarmNote(ctx, open, fmt.Sprintf("Free space recovered to %.1f%%", h.FreePct))
		delete(st.openID, serverID)
	}
	return nil
}

package server

// The management side's link.Sink: what recording servers report. Detection
// events become alarms here (the camera's alert setting and the alarm
// grouping rule), stream status becomes Camera Offline alarms and MQTT's
// online sensors, storage health becomes the Storage alarm, and follow-up
// frames become AI scene descriptions.

import (
	"context"
	"fmt"
	"log/slog"
	"strings"
	"sync"
	"time"

	"sentinel-linux/internal/link"
	"sentinel-linux/internal/store"
)

const offlineAfter = 60 * time.Second

// Sink is what recording servers report to.
func (s *Server) Sink() link.Sink { return sink{s} }

type sink struct{ s *Server }

func (k sink) Event(ctx context.Context, e link.Event) error {
	s := k.s
	switch e.Type {
	case link.EventActivity:
		if e.Activity != nil {
			s.publishActivity(e.CameraID, e.Activity.Kind)
		}
		return nil
	case link.EventFrames:
		if e.Frames != nil {
			go s.describeEvent(e.CameraID, *e.Frames)
		}
		return nil
	}
	if e.Ephemeral {
		return nil
	}
	// At-least-once delivery: skip what was handled already.
	seen, err := s.Store.LinkMessageSeen(ctx, e.ID)
	if err != nil {
		return err
	}
	if seen {
		return nil
	}
	switch e.Type {
	case link.EventDetection:
		if e.Detection != nil {
			s.onDetection(ctx, e.CameraID, *e.Detection)
		}
	case link.EventThumbnail:
		if e.Thumbnail != nil {
			if err := s.Store.SetEventThumbnail(ctx, e.Thumbnail.EventID, e.Thumbnail.File); err != nil {
				slog.Error("save event thumbnail", "err", err)
			}
			s.publishEventUpdated(e.Thumbnail.EventID)
			s.thumbnailArrived(e.Thumbnail.EventID) // wave16.go: appearance, faces, plates, semantic
		}
	case link.EventStorageLow, link.EventStorageRecovered:
		if e.Storage != nil {
			if err := s.onStorage(ctx, e.ServerID, e.Type, *e.Storage); err != nil {
				return err
			}
		}
	case link.EventAudit:
		if e.Audit != nil {
			if err := s.onForwardedAudit(ctx, e.ServerID, *e.Audit); err != nil {
				return err
			}
		}
	default:
		slog.Warn("unknown event from recording server", "type", e.Type)
	}
	if err := s.Store.MarkLinkMessage(ctx, e.ID); err != nil {
		slog.Error("link inbox", "err", err)
	}
	return nil
}

func (k sink) Status(st link.ServerStatus) {
	k.s.noteStatus(st)
	k.s.checkCameraHealth(k.s.ctxOrBackground(), st)
}

// MARK: - Detection events → alarms

// Alert modes (cameras.alert_on).
const (
	alertAuto    = 0
	alertMotion  = 1
	alertObjects = 2 // people & vehicles
	alertPeople  = 3
)

// alertMode resolves "auto": people & vehicles when the camera's recording
// server has the person/vehicle detector, else any motion.
func (s *Server) alertMode(c *store.Camera) int {
	if c.AlertOn != alertAuto {
		return c.AlertOn
	}
	if st, _ := s.statusOf(c.RecorderID); st.Capabilities.Objects {
		return alertObjects
	}
	return alertMotion
}

// onDetection indexes a recorded event and raises or merges its alarm.
func (s *Server) onDetection(ctx context.Context, cameraID string, d link.Detection) {
	cam, err := s.Store.Camera(ctx, cameraID)
	if err != nil {
		return // deleted meanwhile
	}
	ev := &store.Event{ID: d.EventID, CameraID: cam.ID, Kind: d.Kind, Label: d.Label, Score: d.Score, Box: d.Box, CreatedAt: d.CreatedAt, TrackID: d.TrackID}
	if err := s.Store.IndexEvent(ctx, ev); err != nil {
		slog.Error("save detection event", "err", err)
		return
	}
	s.publishEventNew(cam, ev)
	at, mergeSince := time.UnixMilli(d.At), time.UnixMilli(d.MergeSince)
	in := store.AlarmInput{CameraID: cam.ID, CameraName: cam.Name, Kind: d.Kind, EventID: ev.ID, At: at, MergeSince: mergeSince,
		Origin: "Automatically generated by video analytics"}
	var logNew func()
	switch d.Source {
	case link.SourceMotion:
		// People/vehicle modes: motion is logged as an event, but only a
		// detection raises an alarm.
		if s.alertMode(cam) != alertMotion {
			return
		}
		in.Title, in.Severity = "Motion detected", "Warning"
		in.Detail = fmt.Sprintf("%s detected motion at %s.", cam.Name, at.Format("3:04:05 PM"))
		logNew = func() { slog.Info("motion alarm", "camera", cam.Name, "score", fmt.Sprintf("%.3f", d.Score)) }
	case link.SourceObjects:
		if d.Kind == "Loitering" { // a person track that stayed (WAVE16): alarms like the camera's own
			in.Title, in.Severity, _ = cameraEventAlarm(cam, d.Kind)
			in.Detail = fmt.Sprintf("%s: %s at %s.", cam.Name, d.Summary, at.Format("3:04:05 PM"))
			logNew = func() { slog.Info("loitering alarm", "camera", cam.Name, "track", d.TrackID) }
			break
		}
		mode := s.alertMode(cam)
		if !((d.Kind == "Person" && (mode == alertObjects || mode == alertPeople)) || (d.Kind == "Vehicle" && mode == alertObjects)) {
			return
		}
		in.Title, in.Severity = "Person detected", "Critical"
		if d.Kind == "Vehicle" {
			in.Title, in.Severity = "Vehicle detected", "Warning"
		}
		in.Detail = fmt.Sprintf("%s detected a %s at %s.", cam.Name, strings.ToLower(d.Label), at.Format("3:04:05 PM"))
		logNew = func() {
			slog.Info("detection alarm", "camera", cam.Name, "kind", d.Kind, "label", d.Label, "score", d.Score)
		}
	case link.SourceAudio:
		// Every audio event is logged. A classified threat (gunshot, glass
		// break, scream, alarm sound) always alarms; the loudness baseline
		// alarms only when the camera's alarm mode is "any motion", like
		// motion itself.
		if d.Label == "Loud noise" && s.alertMode(cam) != alertMotion {
			return
		}
		in.Title, in.Severity = audioAlarm(d.Label)
		in.Detail = fmt.Sprintf("%s heard: %s at %s.", cam.Name, strings.ToLower(d.Label), at.Format("3:04:05 PM"))
		logNew = func() { slog.Info("audio alarm", "camera", cam.Name, "label", d.Label, "score", d.Score) }
	case link.SourceLines:
		zones, _ := s.Store.CameraZones(ctx, cam.ID)
		title, severity, detail, ok := lineCrossAlarm(cam.Name, zones, d, at)
		if !ok {
			return // an Info line: the event is logged, no alarm
		}
		in.Title, in.Severity, in.Detail = title, severity, detail
		logNew = func() { slog.Info("line crossing alarm", "camera", cam.Name, "line", d.Rule, "label", d.Label) }
	case link.SourceCamera:
		title, severity, ok := cameraEventAlarm(cam, d.Kind)
		if !ok {
			return
		}
		in.Title, in.Severity = title, severity
		in.Detail = fmt.Sprintf("%s's built-in analytics reported %s at %s.", cam.Name, d.Summary, at.Format("3:04:05 PM"))
		in.Origin = "Reported by the camera's built-in analytics (ONVIF)"
		logNew = func() {
			slog.Info("camera analytics alarm", "camera", cam.Name, "kind", d.Kind, "rule", d.Rule, "topic", d.Topic)
		}
	default:
		return
	}
	alarm, isNew, err := s.Store.RaiseAlarm(ctx, in)
	if err != nil {
		return
	}
	_ = s.Store.SetEventAlarm(ctx, ev.ID, alarm.ID)
	if isNew {
		logNew()
	}
}

// cameraEventAlarm decides whether a camera-reported event raises an alarm.
// Rules the installer drew on the camera (lines, zones, tamper) always do.
// People and vehicles follow the camera's alert setting, where "auto" means
// people & vehicles: the camera is the detector, whatever is installed here.
func cameraEventAlarm(c *store.Camera, kind string) (title, severity string, ok bool) {
	mode := c.AlertOn
	if mode == alertAuto {
		mode = alertObjects
	}
	switch kind {
	case "Person":
		return "Person detected", "Critical", mode == alertObjects || mode == alertPeople
	case "Vehicle":
		return "Vehicle detected", "Warning", mode == alertObjects
	case "Line crossing":
		return "Line crossed", "Critical", true
	case "Intrusion":
		return "Intrusion detected", "Critical", true
	case "Loitering":
		return "Loitering detected", "Warning", true
	case "Tamper":
		return "Camera tampering", "Critical", true
	}
	return "", "", false
}

// MARK: - Stream status → Camera Offline alarms

type healthState struct {
	mu          sync.Mutex
	lastReady   map[string]time.Time
	offlineOpen map[string]string // camera → open Camera Offline alarm id
}

// checkCameraHealth runs on every status report (every 15 s): it publishes
// each camera's online state and raises a Camera Offline alarm after 60 s
// without video, noting on it when video returns.
func (s *Server) checkCameraHealth(ctx context.Context, status link.ServerStatus) {
	if !status.Media.Running {
		return
	}
	cams, err := s.Store.Cameras(ctx)
	if err != nil {
		return
	}
	st := &s.health
	st.mu.Lock()
	if st.lastReady == nil {
		st.lastReady, st.offlineOpen = map[string]time.Time{}, map[string]string{}
	}
	st.mu.Unlock()
	now := time.Now()
	for _, c := range cams {
		if c.RecorderID != status.ServerID {
			continue // another recording server's camera
		}
		ready := status.Cameras[c.ID].Ready
		s.publishCameraOnline(c.ID, ready)
		st.mu.Lock()
		last, seen := st.lastReady[c.ID]
		open := st.offlineOpen[c.ID]
		if ready {
			st.lastReady[c.ID] = now
			delete(st.offlineOpen, c.ID)
		}
		st.mu.Unlock()
		switch {
		case ready && open != "":
			_ = s.Store.AddAlarmNote(ctx, open, "Video restored")
		case !ready && seen && open == "" && now.Sub(last) >= offlineAfter:
			a, _, err := s.Store.RaiseAlarm(ctx, store.AlarmInput{
				CameraID: c.ID, CameraName: c.Name, Kind: "Camera Offline", Title: "Camera offline", Severity: "Critical",
				Detail: fmt.Sprintf("%s stopped delivering video at %s.", c.Name, last.Format("3:04 PM")),
				At:     now, Origin: "Automatically generated by stream supervisor",
			})
			if err == nil {
				st.mu.Lock()
				st.offlineOpen[c.ID] = a.ID
				st.mu.Unlock()
				slog.Warn("camera offline", "camera", c.Name)
			}
		}
	}
}

// MARK: - Follow-up frames → AI scene description

// describeEvent asks Claude for a description of a person/vehicle event,
// stores it on the event and copies it onto the event's alarm.
func (s *Server) describeEvent(cameraID string, f link.Frames) {
	if len(f.JPEGs) == 0 || !s.aiReady() || !s.aiTakeBudget() {
		return
	}
	client, err := s.aiClient()
	if err != nil {
		return
	}
	ctx := s.ctxOrBackground()
	camName := "Camera"
	if cam, err := s.Store.Camera(ctx, cameraID); err == nil {
		camName = cam.Name
	}
	actx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	a, err := client.AnalyzeScene(actx, f.JPEGs, f.Kind)
	if err != nil {
		s.setAIError(err)
		slog.Warn("AI description failed", "camera", camName, "err", err)
		return
	}
	s.setAIError(nil)
	_ = s.Store.SetEventAnalysis(ctx, f.EventID, a.Description, a.Threat, a.Anomaly, a.Reason, strings.Join(a.Tags, ", "))
	s.publishEventUpdated(f.EventID)
	if ev, err := s.Store.Event(ctx, f.EventID); err == nil && ev.AlarmID != "" {
		detail := camName + ": " + a.Description
		severity := ""
		if a.Threat == "elevated" || a.Threat == "high" {
			severity = "Critical"
			if a.Reason != "" {
				detail += " (" + a.Threat + " threat: " + a.Reason + ")"
			}
		}
		_ = s.Store.UpdateAlarmDetail(ctx, ev.AlarmID, detail, severity)
	}
}

func (s *Server) handleEvidenceFile(w http.ResponseWriter, r *http.Request) {
	ev, err := s.Store.EvidenceByID(r.Context(), r.PathValue("id"))
	if err != nil {
		writeError(w, http.StatusNotFound, "evidence not found")
		return
	}
	f, err := os.Open(filepath.Join(s.evidenceDir(), filepath.Base(ev.File)))
	if err != nil {
		writeError(w, http.StatusNotFound, "evidence file missing")
		return
	}
	defer f.Close()
	info, _ := f.Stat()
	s.audit(r, "Evidence", "Downloaded evidence", ev.CaseID)
	w.Header().Set("Content-Type", "video/mp4")
	w.Header().Set("Content-Disposition", `attachment; filename="`+ev.CaseID+`.mp4"`)
	w.Header().Set("X-Content-SHA256", ev.SHA256)
	http.ServeContent(w, r, ev.CaseID+".mp4", info.ModTime(), f)
}

func lower(s string) string {
	b := []byte(s)
	for i, c := range b {
		if c >= 'A' && c <= 'Z' {
			b[i] = c + 32
		}
	}
	return string(b)
}
